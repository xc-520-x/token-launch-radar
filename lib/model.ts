// The token radar's model: one sealed snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every
// other rankable pre-token protocol below it: the early rows the radar exists to find. A protocol is
// pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol). Live-token
// protocols are kept apart and shown with the market's own values, never mixed into the ranking — but
// they calibrate it: each category's base multiple is the median market-cap-to-TVL ratio of the
// live-token protocols in that category, shrunk toward the global median where the sample is small.
// No protocol name is ever special-cased: the same functions score every row.
//
//   multiple     = category median mcap/TVL (each ratio winsorized at 3.0, so one thin
//                  token cannot set a category), shrunk toward the global median with a prior
//                  of 8 observations, clamped to [0.05, 1.50]; categories with no live sample
//                  use the global median
//   growthMult   = 1 + clamp(change_7d, -60, 120) / 100 x 0.5
//   maturityMult = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365 days)
//   breadthMult  = 1 + 0.02 x min(chains - 1, 5)            (at most 1.10)
//   implied      = max(1, round(tvl_usd x multiple x growthMult x maturityMult x breadthMult))
//
// Farm plans are derived from the protocol's own record (category, first chain, TVL, age): the
// action fits the category, the gas fits the chain, the capital fits the TVL tier, the hold fits
// the age. Every step states what it costs and how long it takes.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

